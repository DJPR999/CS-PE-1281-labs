print("Welcome to the Shop Floor.")
name = input("Operator name: ")
print(f"Hello, {name}! Ready for shift.")

"""IT-10"""

accept = 0
rework = 0
scrap = 0

for i in range(10):
    diameter = float(input(f"Part {i + 1} diameter (mm): "))

    if 24.8 <= diameter <= 25.2:
        accept += 1
    elif diameter > 25.2:
        rework += 1
    else:
        scrap += 1

print(f"\nBatch Report -> ACCEPT: {accept} | REWORK: {rework} | SCRAP: {scrap}")

"""IT-8"""

total = int(input("Total parts: "))
size = int(input("Box size: "))

boxes = total // size
loose = total % size

print(f"Full boxes: {boxes}")
print(f"Loose parts: {loose}")
print(f"Audit check: {boxes * size + loose == total}")

"""IT-6"""

accept = 0
rework = 0
scrap = 0
box_size = 4

for i in range(10):
    diameter = float(input(f"Part {i + 1} diameter (mm): "))

    if 24.8 <= diameter <= 25.2:
        accept += 1
    elif diameter > 25.2:
        rework += 1
    else:
        scrap += 1

boxes = accept // box_size
loose = accept % box_size

print("\n--- END OF SHIFT SUMMARY ---")
print(f"Bin Counts -> ACCEPT: {accept} | REWORK: {rework} | SCRAP: {scrap}")
print(f"Packing    -> Full Boxes (of {box_size}): {boxes} | Loose Parts: {loose}")
print(f"Audit      -> {boxes * box_size + loose == accept}")